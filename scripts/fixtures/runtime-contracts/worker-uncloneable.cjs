const assert = require('node:assert/strict');
const { markAsUncloneable, MessageChannel, Worker } = require('node:worker_threads');
const marked = { retained: 42 };
assert.equal(markAsUncloneable(marked), undefined);
assert.deepEqual(marked, { retained: 42 });
const channel = new MessageChannel();
const rejects = value => {
  assert.throws(() => structuredClone(value), { name: 'DataCloneError' });
  assert.throws(() => channel.port1.postMessage(value), { name: 'DataCloneError' });
};
rejects(marked);
rejects({ nested: [marked] });
rejects(new Map([[marked, 1]]));
rejects(new Set([marked]));
rejects(new Error('marked cause', { cause: marked }));
assert.throws(() => new Worker('', { eval: true, workerData: { marked } }), { name: 'DataCloneError' });
let reads = 0;
assert.deepEqual(structuredClone({ get once() { reads++; return { value: 1 }; } }), { once: { value: 1 } });
assert.equal(reads, 1);
rejects({ get returned() { return marked; } });
const cyclic = { regular: 1 }; cyclic.self = cyclic;
const copied = structuredClone(cyclic);
assert.equal(copied.self, copied);
const original = { date: new Date(1234), regex: /test/gi, bytes: new Uint8Array([1, 2]), error: new TypeError('typed') };
const ordinary = structuredClone(original);
assert.equal(ordinary.date.getTime(), 1234);
assert.equal(ordinary.regex.source, 'test');
assert.deepEqual([...ordinary.bytes], [1, 2]);
assert.equal(ordinary.error.name, 'TypeError');
const bytes = new ArrayBuffer(8);
markAsUncloneable(bytes);
assert.equal(structuredClone(bytes, { transfer: [bytes] }).byteLength, 8);
assert.equal(bytes.byteLength, 0);
for (const value of [null, undefined, 1, 'value']) markAsUncloneable(value);
channel.port1.close(); channel.port2.close();
console.log('WORKER_UNCLONEABLE_PASS');
